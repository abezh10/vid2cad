"""Top-level translator: walk timeline, dispatch entities, assemble code."""
from __future__ import annotations

from .emit import emit_extrude_feature, UnsupportedFeatureError


class TranslationError(Exception):
    pass


HEADER = '''"""Generated by vid2cad translator from DeepCAD/Fusion JSON."""
import cadquery as cq

result = None
'''


def translate_design(data: dict, strict: bool = False) -> str:
    """Translate a parsed JSON design dict into a standalone CADQuery Python script.

    The script defines a variable `result` which is the final cq.Workplane solid.

    By default this is forgiving: individual extrudes that hit unsupported features
    are skipped, and the design is considered translated as long as at least one
    extrude succeeded. Pass `strict=True` to revert to fail-fast behavior.
    """
    entities = data.get("entities") or {}
    sequence = data.get("sequence") or []
    if not sequence:
        raise TranslationError("empty sequence")

    sketches: dict[str, dict] = {}
    code_lines: list[str] = [HEADER.rstrip()]
    skipped_notes: list[str] = []
    sketch_var_counter = [0]
    n_extrudes_emitted = 0

    for step in sequence:
        stype = step.get("type")
        entity_id = step.get("entity")
        entity = entities.get(entity_id)
        if entity is None:
            if strict:
                raise TranslationError(f"missing entity {entity_id!r}")
            continue

        if stype == "Sketch":
            sketches[entity_id] = entity
            continue

        if stype == "ExtrudeFeature":
            try:
                lines = emit_extrude_feature(
                    entity, sketches, result_var="result",
                    sketch_var_counter=sketch_var_counter,
                )
            except UnsupportedFeatureError as e:
                if strict:
                    raise TranslationError(f"extrude {entity_id!r}: {e}") from e
                skipped_notes.append(f"# skipped extrude {entity_id}: {e}")
                continue
            code_lines.extend(lines)
            n_extrudes_emitted += 1
            continue

        if strict:
            raise TranslationError(f"unsupported timeline entry type: {stype!r}")
        skipped_notes.append(f"# skipped timeline entry of type {stype!r}")

    if n_extrudes_emitted == 0:
        raise TranslationError("no usable extrude features")

    if skipped_notes:
        code_lines.append("")
        code_lines.extend(skipped_notes)

    return "\n".join(code_lines) + "\n"
